<?php

namespace App\Imports;

use App\Models\Domain;
use Maatwebsite\Excel\Concerns\ToModel;
use Maatwebsite\Excel\Concerns\WithStartRow;

class DomainImport implements ToModel, WithStartRow
{
    /**
     * Excel row 1 contains the headers.
     * Start importing from row 2.
     */
    public function startRow(): int
    {
        return 2;
    }


    /**
     * Import one Excel row.
     */
    public function model(array $row)
    {
        // Skip completely empty rows
        if (
            empty($row[0]) &&
            empty($row[1]) &&
            empty($row[2])
        ) {
            return null;
        }


        return new Domain([

            /*
            |--------------------------------------------------------------------------
            | 1. Domain ID
            |--------------------------------------------------------------------------
            */

            'domain_id' =>
                $this->value($row, 0),


            /*
            |--------------------------------------------------------------------------
            | 2. Domain Code
            |--------------------------------------------------------------------------
            */

            'domain_code' =>
                $this->value($row, 1),


            /*
            |--------------------------------------------------------------------------
            | 3. Domain Name
            |--------------------------------------------------------------------------
            */

            'name' =>
                $this->value($row, 2),


            /*
            |--------------------------------------------------------------------------
            | 4. Slug
            |--------------------------------------------------------------------------
            */

            'slug' =>
                $this->value($row, 3),


            /*
            |--------------------------------------------------------------------------
            | 5. Purpose
            |--------------------------------------------------------------------------
            */

            'purpose' =>
                $this->value($row, 4),


            /*
            |--------------------------------------------------------------------------
            | 6. Scope
            |--------------------------------------------------------------------------
            */

            'scope' =>
                $this->value($row, 5),


            /*
            |--------------------------------------------------------------------------
            | 7. Business Owner
            |--------------------------------------------------------------------------
            */

            'business_owner' =>
                $this->value($row, 6),


            /*
            |--------------------------------------------------------------------------
            | 8. Applicable Industries #1
            |--------------------------------------------------------------------------
            */

            'applicable_industries' =>
                $this->value($row, 7),


            /*
            |--------------------------------------------------------------------------
            | 9. Applicable Technologies #1
            |--------------------------------------------------------------------------
            */

            'applicable_technologies' =>
                $this->value($row, 8),


            /*
            |--------------------------------------------------------------------------
            | 10. Description
            |--------------------------------------------------------------------------
            */

            'description' =>
                $this->value($row, 9),


            /*
            |--------------------------------------------------------------------------
            | 11. Display Order
            |--------------------------------------------------------------------------
            */

            'display_order' =>
                $this->value($row, 10) !== null &&
                $this->value($row, 10) !== ''
                    ? (int) $this->value($row, 10)
                    : 0,


            /*
            |--------------------------------------------------------------------------
            | 12. Status
            |--------------------------------------------------------------------------
            */

            'status' =>
                $this->value($row, 11) ?: 'Active',


            /*
            |--------------------------------------------------------------------------
            | 13. Version
            |--------------------------------------------------------------------------
            */

            'version' =>
                $this->value($row, 12),


            /*
            |--------------------------------------------------------------------------
            | 14. Domain Name #2
            |--------------------------------------------------------------------------
            */

            'domain_name' =>
                $this->value($row, 13),


            /*
            |--------------------------------------------------------------------------
            | 15. Short Overview
            |--------------------------------------------------------------------------
            */

            'short_overview' =>
                $this->value($row, 14),


            /*
            |--------------------------------------------------------------------------
            | 16. Business Objectives #1
            |--------------------------------------------------------------------------
            */

            'business_objectives' =>
                $this->value($row, 15),


            /*
            |--------------------------------------------------------------------------
            | 17. Business Objectives #2
            |--------------------------------------------------------------------------
            */

            'business_objectives_2' =>
                $this->value($row, 16),


            /*
            |--------------------------------------------------------------------------
            | 18. Business Risks
            |--------------------------------------------------------------------------
            */

            'business_risks' =>
                $this->value($row, 17),


            /*
            |--------------------------------------------------------------------------
            | 19. Key Capabilities
            |--------------------------------------------------------------------------
            */

            'key_capabilities' =>
                $this->value($row, 18),


            /*
            |--------------------------------------------------------------------------
            | 20. Typical Stakeholders
            |--------------------------------------------------------------------------
            */

            'typical_stakeholders' =>
                $this->value($row, 19),


            /*
            |--------------------------------------------------------------------------
            | 21. Applicable Industries #2
            |--------------------------------------------------------------------------
            */

            'applicable_industries_2' =>
                $this->value($row, 20),


            /*
            |--------------------------------------------------------------------------
            | 22. Applicable Technologies #2
            |--------------------------------------------------------------------------
            */

            'applicable_technologies_2' =>
                $this->value($row, 21),


            /*
            |--------------------------------------------------------------------------
            | 23. Keywords
            |--------------------------------------------------------------------------
            */

            'keywords' =>
                $this->value($row, 22),


            /*
            |--------------------------------------------------------------------------
            | 24. Tags
            |--------------------------------------------------------------------------
            */

            'tags' =>
                $this->value($row, 23),


            /*
            |--------------------------------------------------------------------------
            | 25. Why This Domain Matters
            |--------------------------------------------------------------------------
            */

            'why_domain_matters' =>
                $this->value($row, 24),


            /*
            |--------------------------------------------------------------------------
            | 26. Common Challenges
            |--------------------------------------------------------------------------
            */

            'common_challenges' =>
                $this->value($row, 25),


            /*
            |--------------------------------------------------------------------------
            | 27. Related Domains
            |--------------------------------------------------------------------------
            */

            'related_domains' =>
                $this->value($row, 26),


            /*
            |--------------------------------------------------------------------------
            | 28. Related Frameworks
            |--------------------------------------------------------------------------
            */

            'related_frameworks' =>
                $this->value($row, 27),

        ]);
    }


    /**
     * Safely get an Excel column value.
     */
    private function value(array $row, int $index): ?string
    {
        if (!isset($row[$index])) {
            return null;
        }

        $value = trim((string) $row[$index]);

        return $value === ''
            ? null
            : $value;
    }
}